def _sample(name, conversion, spec):
    """A value to fill *name* with: its brace word for one meant as written, a
    number for one written with a format spec, else a text naming it."""
    if conversion == "=":
        return "{" + name + "}"
    return 1234 if spec else f"<{name}>"


def _written(value, conversion, spec):
    """*value* as the check writes it: its conversion, then its format spec."""
    value = {"r": repr, "s": str, "a": ascii}.get(conversion, lambda x: x)(value)
    return format(value, spec) if spec else value


