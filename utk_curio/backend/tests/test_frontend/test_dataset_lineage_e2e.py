"""Playwright E2E: drawing one edge changes a dataset's lineage.

The Data Catalog detail panel's Lineage tab claims to show, *live*, which nodes
consume a dataset. That claim is not backed by anything persisted: the consumer
list is recomputed from the open canvas on every render, through
``FlowContext -> useDatasetLineage -> selectDatasetDownstreamUsage``. So a test
that never opens a browser can prove the resolver is correct but not that the
panel is wired to it - and the wiring is the part that breaks, because the
lineage is derived state three providers away from the nodes it reads.

The test makes one user gesture, a single edge from a dataset's loader node to a
Data Transformation node, and checks three surfaces that must all follow it:

* **The panel, with nothing saved.** "Consumed by (0)" becomes "Consumed by
  (1)". Nothing was written to the server between the two reads, so the change
  can only have come through the canvas. This is also where the ``#141``
  invariant is visible for free: before the edge, a dropped-but-unconnected
  loader is the dataset's *source*, not a consumer, so it registers no usage.
* **The catalog card's connection badge.** ``DatasetConnectionBadge`` renders
  nothing until the dataset has connections and then reads "1v". It is fed by
  the same hook, from a different component, in a different subtree.
* **The server, after a save.** ``GET /api/datasets/<id>/usage`` resolves
  consumers from the persisted spec with a *second, independent* implementation
  of the carrier rule (``_dataset_consumer_nodes_in_spec`` in
  ``application/export.py``, mirroring ``datasetLineageResolver.ts``). Both have
  unit tests; nothing else checks the two agree about the same graph. Asserting
  the same node id from both ends is what makes this worth a browser.

Covered more cheaply elsewhere and deliberately not re-asserted here: every
branch of the resolver, including the stale/unresolved statuses and the
carrier/edge rules, is ``src/tests/services/datasetLineageResolver.test.ts``;
the panel's rendering of a lineage object - the status pills, the "Generated by"
card, the Lineage tab switch - is ``src/tests/components/DatasetDetailPanel.test.tsx``,
with the backend-usage fallback in ``DatasetDetailPanelUsageFallback.test.tsx``;
``consumerNodeCount``, the empty-usage case and ``upstreamInputs`` persistence
are ``tests/test_datasets/test_dataset_usage.py`` and
``test_computed_namespacing_and_lineage.py``; the drawer's listing, search and
install are ``test_data_catalog.py``; and the drag/drop/connect gestures
themselves are ``test_canvas_authoring_e2e.py``.

Not covered: a consumer that has actually *run*. Its pill would read Active, but
getting there means driving the sandbox, and the Jest panel test already asserts
that rendering from a fixture. The pill this test sees is Stale, which is the
correct and deterministic outcome of the gesture it makes - see step 5. The
run itself - loader executes, data crosses the edge, consumer asserts on it -
is ``test_dataset_catalog_datasets_e2e.py``, for every catalog dataset.

Run::

    CURIO_TESTING=1 pytest utk_curio/backend/tests/test_frontend/test_dataset_lineage_e2e.py -v
"""
from __future__ import annotations

import re
from typing import TYPE_CHECKING

from playwright.sync_api import expect

from .utils import (
    accept_confirm_dialog,
    api_json,
    canvas_node_type,
    connect_nodes,
    dismiss_toasts,
    drag_to_canvas,
    open_tools_palette,
    require_project_page,
    require_user_auth,
    save_dataflow,
    save_workflow_test_screenshot,
    require_owner_view,
    stub_login_and_enter_workflow,
)

if TYPE_CHECKING:
    from .utils import FrontendPage

# The CSV hub dataset, for the same reason test_canvas_authoring_e2e.py picks it:
# its generated loader only needs pandas. Nothing here runs a node, but keeping
# the two tests on the same dataset keeps the install path identical.
DATASET_ID = "data.urbanlab.acs-neighborhood-profile"
DATASET_TITLE = "ACS Neighborhood Profile"

DRAWER_ROOT = '[data-curio-dataset-catalog-drawer="true"]'
# The "Adding…" placeholder is an <article role="status"> carrying the same title
# as the real card, so every card locator has to exclude it.
CARD = 'article:not([role="status"])'

LOADER_TYPE = "curio.builtin/data-loading"
TRANSFORM_TYPE = "curio.builtin/data-transformation"
TRANSFORM_TILE = "#step-transformation"
# The label the node registry gives curio.builtin/data-transformation, which is
# what the consumer card names the node (`resolveNodeLabel` wins over the raw
# type). Asserting the label rather than the id also proves the panel resolved
# the node against the registry instead of printing a coordinate at the user.
TRANSFORM_LABEL = "Data Transformation"

# A node is 525x350 at zoom 1 in a 1280x720 viewport, so anything closer than
# ~600px apart horizontally overlaps and the later node's body covers the
# earlier one's output handle - which makes the connection drag a silent no-op.
POS_LOADER = (150, 150)
POS_TRANSFORM = (760, 150)

EMPTY_USAGE = "No nodes or dataflows are currently using this dataset."

# No dataset teardown, deliberately. Installing a *hub* dataset copies it into
# ``.curio/users/<id>/datasets/`` (``mutations.install_dataset`` ->
# ``install_dataset_from_catalog``), and that copy cannot be removed: the
# account-level DELETE runs ``unpublish_dataset`` first, which 403s because this
# user is not the publisher of a committed catalog dataset. The copy is harmless
# to a re-run because installed-ness is scoped to a dataflow, not to the store,
# so a fresh project still shows the card offering "Add to project".


def _unversioned(node_type: str | None) -> str:
    """Strip the ``@<major>`` a descriptor id may carry.

    A dataset drop goes through ``createCodeNode(NodeType.DATA_LOADING)`` with
    the bare id while a palette drag carries the descriptor's full coordinate,
    so the same kind arrives in both forms.
    """
    return (node_type or "").split("@", 1)[0]


def _drawer(page):
    root = page.locator(DRAWER_ROOT)
    root.wait_for(state="attached", timeout=15000)
    # aria-hidden IS the presented signal: until the rAF flips it, every role
    # query inside the subtree returns zero matches.
    expect(root).to_have_attribute("aria-hidden", "false", timeout=10000)
    dialog = page.get_by_role("dialog").filter(
        has=page.get_by_role("heading", name="Data Catalog", exact=True)
    )
    expect(dialog).to_be_visible(timeout=10000)
    return dialog


def _close_drawer(page):
    # This drawer has no Escape handler, so close through the header button.
    page.locator(DRAWER_ROOT).locator("header").get_by_role(
        "button", name="Close Data Catalog drawer"
    ).click()
    expect(page.locator(DRAWER_ROOT)).to_have_count(0, timeout=5000)


def _add_dataset_from_catalog(page, palette):
    """Add the hub dataset to the open dataflow and leave the palette showing it.

    Returns once the palette row exists, which is what the drag needs.
    """
    palette.get_by_role("button", name="Browse Data Catalog +").click(force=True)
    drawer = _drawer(page)
    card = drawer.locator(f'{CARD}[data-dataset-id="{DATASET_ID}"]')
    expect(card).to_have_count(1, timeout=15000)

    card.get_by_role("button", name="Add to project", exact=True).click()
    with page.expect_response(
        lambda r: "/datasets/install" in r.url and r.request.method == "POST" and r.ok,
        timeout=60000,
    ):
        # The Data catalog confirms an add now (#196), so the card click only
        # opens the dialog - the POST follows the confirm.
        accept_confirm_dialog(
            page, title=re.compile(r"^Add "), button="Add to project"
        )

    # Re-resolve rather than reuse the handle: the install flips origin
    # hub -> imported, which changes the React key so the card is replaced.
    expect(
        drawer.locator(f'{CARD}[data-dataset-id="{DATASET_ID}"]').get_by_role(
            "button", name="Remove from project", exact=True
        )
    ).to_be_visible(timeout=20000)

    _close_drawer(page)

    row = page.locator(f'#datasets-palette [data-dataset-id="{DATASET_ID}"]')
    expect(row).to_have_count(1, timeout=20000)
    return row


def _open_lineage_tab(page):
    """Open the drawer, open the dataset's detail modal on the Lineage tab.

    Returns ``(card, center, sidebar)``: the drawer card the modal was opened
    from (it stays mounted behind the overlay and carries the connection badge),
    the modal's center column and its info sidebar.

    Both columns render the same lineage strings, so every assertion has to be
    scoped to one of them - an unscoped ``get_by_text`` on the Lineage tab is
    strict-mode-ambiguous.
    """
    page.get_by_role("button", name="Data ⏷", exact=True).click(force=True)
    page.get_by_role("button", name="Data Catalog", exact=True).click()
    drawer = _drawer(page)

    card = drawer.locator(f'{CARD}[data-dataset-id="{DATASET_ID}"]')
    expect(card).to_have_count(1, timeout=20000)
    # The trigger is the card's format avatar, whose accessible name carries the
    # format abbreviation ("View <title> (CSV) details").
    card.locator(f'button[aria-label^="View {DATASET_TITLE} ("]').click()

    # The modal fetches GET /api/datasets/<id> before rendering the panel body,
    # so gate on the panel's own tab strip rather than the modal frame.
    tabs = page.get_by_role("navigation", name="Dataset detail sections")
    expect(tabs).to_be_visible(timeout=20000)
    tabs.get_by_role("button", name="Lineage", exact=True).click()

    center = page.locator('section[aria-label="Dataset content"]')
    sidebar = page.get_by_role("complementary", name="Dataset info")
    # The tab buttons carry no aria-selected, so the center column's own heading
    # is the only signal that the switch landed.
    expect(center.get_by_role("heading", name=re.compile(r"^Dataflows"))).to_be_visible(
        timeout=10000
    )
    return card, center, sidebar


def _close_details_and_drawer(page):
    # ModalShell's own dismiss, located by excluding the toasts rather than by
    # role+name: every toast's close button carries the same aria-label, so
    # get_by_role("button", name="Close") is strict-mode-ambiguous for as long as
    # the "Added <dataset>" / "Created a Data Loading node" toasts are on screen.
    # They are the ones marked data-dismiss, so this leaves exactly the modal X.
    page.locator('button[aria-label="Close"]:not([data-dismiss="toast"])').click()
    expect(
        page.get_by_role("navigation", name="Dataset detail sections")
    ).to_have_count(0, timeout=10000)
    _close_drawer(page)


def test_wiring_a_consumer_grows_dataset_lineage(
    app_frontend: "FrontendPage",
    current_server: str,
    page,
):
    """One edge, and the lineage panel, the card badge and the server all move."""
    require_project_page()
    require_user_auth()

    # Before navigating: the drawer slides via translate3d, so to_be_visible is
    # not a gate on its own, and the provider reads prefers-reduced-motion
    # through useSyncExternalStore.
    page.emulate_media(reduced_motion="reduce")
    session = stub_login_and_enter_workflow(
        page,
        frontend_url=app_frontend.base_url,
        backend_url=current_server,
        name="Lineage Wiring",
        username="lineage_wiring",
        project_name="Dataset Lineage",
    )
    require_owner_view(page)
    token = session["token"]
    project_id = session["project"]["id"]

    # 1. A DATASET IN THE DATAFLOW, and a loader node for it. The palette has to
    #    stay open past the drawer, because the row it renders is what gets
    #    dragged onto the canvas.
    palette = open_tools_palette(page, "datasets")
    dataset_row = _add_dataset_from_catalog(page, palette)

    loader_id = drag_to_canvas(page, dataset_row, at=POS_LOADER)
    assert _unversioned(canvas_node_type(page, loader_id)) == LOADER_TYPE, (
        "dropping a dataset must take the dataset branch of handleDrop and "
        "create a Data Loading node"
    )

    # 2. A NODE TO CONSUME IT, not yet connected to anything.
    transform_id = drag_to_canvas(page, page.locator(TRANSFORM_TILE), at=POS_TRANSFORM)
    assert _unversioned(canvas_node_type(page, transform_id)) == TRANSFORM_TYPE

    # 3. BEFORE. Two nodes and the dataset are on the canvas, but no edge, so the
    #    loader is the dataset's source and nothing consumes it (#141).
    card, center, sidebar = _open_lineage_tab(page)
    expect(center.get_by_text("Consumed by (0)")).to_be_visible(timeout=10000)
    expect(center.get_by_text(EMPTY_USAGE)).to_be_visible()
    expect(sidebar.get_by_text(EMPTY_USAGE).first).to_be_visible()
    expect(sidebar.get_by_text("Downstream usage (0)")).to_be_visible()
    # A hub dataset that was loaded, not computed: no producer node, so the
    # origin card names the provenance instead of a node.
    expect(center.get_by_text("Imported", exact=True)).to_be_visible()
    expect(center.get_by_text(re.compile(r"^Generated by \S"))).to_have_count(0)
    # ...and no Inputs section: upstreamInputs is written only for a saved node
    # output, so a loaded hub dataset has none and the block must be absent
    # rather than an empty "Inputs (0)".
    expect(center.get_by_text(re.compile(r"^Inputs \("))).to_have_count(0)
    # The badge renders nothing at all while the dataset has no connections.
    expect(card.get_by_text(re.compile(r"\d[↑↓]"))).to_have_count(0)
    # "Add to project" wrote the dataflow's dataset ref into the saved spec, so
    # the backend already lists this dataflow as *using* the dataset - but with
    # no consumer node, which is the "Produced here" row. Owning a dataset is not
    # consuming it, and the section is the one surface where the difference shows.
    usage_section = center.locator('section[aria-label="Projects using this dataset"]')
    expect(usage_section.get_by_text("Used in projects (1)")).to_be_visible(
        timeout=15000
    )
    expect(usage_section.get_by_text("Produced here")).to_be_visible()

    _close_details_and_drawer(page)

    # 4. THE GESTURE. One edge, from the dataset's loader to the transformation.
    #    The edge id is derived, not random, so it doubles as an assertion that
    #    the handles the drag hit were the ones intended.
    edge_id = connect_nodes(page, loader_id, transform_id)
    assert edge_id == f"reactflow__edge-{loader_id}out-{transform_id}in"

    # 5. AFTER, WITH NOTHING SAVED. THE POINT: no request went out between step 3
    #    and here, so a consumer appearing now can only have come through
    #    FlowContext -> useDatasetLineage -> the panel.
    card, center, sidebar = _open_lineage_tab(page)
    expect(center.get_by_text("Consumed by (1)")).to_be_visible(timeout=10000)
    consumer = center.locator("article").filter(has_text=TRANSFORM_LABEL)
    expect(consumer).to_have_count(1)
    # The dataflow is named, so the caption names it rather than saying "Current
    # dataflow" (which is the no-project-name branch).
    expect(consumer).to_contain_text("Dataflow: Dataset Lineage")
    # Stale, not Active, and deterministically so: FlowProvider's onConnect calls
    # markNodeStale on the edge's *target*, because wiring a new input
    # invalidates whatever that node last computed. So the pill is a third thing
    # following the gesture - the live nodeExecStatus map, which also only exists
    # in the browser. (The Active pill is covered from a fixture in the Jest
    # panel test.)
    expect(consumer).to_contain_text("Stale")
    expect(center.get_by_text(EMPTY_USAGE)).to_have_count(0)
    expect(sidebar.get_by_text("Used by 1 node in 1 dataflow")).to_be_visible()
    expect(sidebar.get_by_text("Downstream usage (1)")).to_be_visible()
    # Same hook, different component, different subtree: the card behind the
    # overlay now advertises one downstream connection.
    expect(card.get_by_text("1↓", exact=True)).to_be_visible(timeout=10000)

    # Visual baseline for the panel nobody hand-checks otherwise. Compared at the
    # suite's default tolerance (20% of pixels, 30/255 per channel); the helper
    # pins the ReactFlow viewport through JS first, which the open modal does not
    # block, and writes the baseline on the first run if the file is absent.
    dismiss_toasts(page)
    save_workflow_test_screenshot(
        page, "dataset-lineage",
        test_name="test_wiring_a_consumer_grows_dataset_lineage",
    )

    _close_details_and_drawer(page)

    # 6. AFTER, ON THE SERVER. The backend resolves consumers from the saved spec
    #    with its own copy of the carrier rule; this is the assertion that the
    #    two implementations agree about the graph the user just drew.
    save_dataflow(page)

    # First what the save persisted, then what the backend derives from it. Split
    # in two so a failure says which half broke: the spec write (no edge, or the
    # loader lost its datasetRefs binding) or the consumer resolution.
    spec = api_json(f"{current_server}/api/projects/{project_id}", token)["spec"]
    dataflow = spec["dataflow"]
    assert [(e["source"], e["target"]) for e in dataflow["edges"]] == [
        (loader_id, transform_id)
    ], dataflow["edges"]
    loader = next(n for n in dataflow["nodes"] if n["id"] == loader_id)
    assert DATASET_ID in (loader.get("metadata") or {}).get("datasetRefs", []), (
        "the loader node did not persist its dataset binding, so the backend has "
        f"no carrier to resolve consumers from: {loader.get('metadata')}"
    )

    usage = api_json(f"{current_server}/api/datasets/{DATASET_ID}/usage", token)["dataflows"]
    assert len(usage) == 1, f"expected exactly one dataflow to use the dataset: {usage}"
    assert usage[0]["dataflowId"] == project_id, usage
    assert usage[0]["nodeCount"] == 1, usage
    assert [node["nodeId"] for node in usage[0]["nodes"]] == [transform_id], (
        f"the backend named a different consumer than the canvas did: {usage}"
    )

    # 7. And the panel shows that same consumer arriving from the server: the
    #    usage section is fetched, not derived from the canvas.
    _, center, _ = _open_lineage_tab(page)
    usage_section = center.locator('section[aria-label="Projects using this dataset"]')
    expect(usage_section.get_by_text("Used in projects (1)")).to_be_visible(
        timeout=15000
    )
    expect(usage_section.get_by_role("link", name="Dataset Lineage")).to_be_visible()
    # The row that read "Produced here" in step 3 now names a consumer: same
    # dataflow, same endpoint, one edge later.
    expect(usage_section.get_by_text("Produced here")).to_have_count(0)
    expect(usage_section).to_contain_text("Consumed by")
